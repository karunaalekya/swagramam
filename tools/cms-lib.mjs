// Shared helpers for the Sanity build (cms-seed.mjs, cms-build.mjs, tests).
import fs from "node:fs"; import vm from "node:vm";
export const ROOT = new URL("../", import.meta.url);
export const read = p => fs.readFileSync(new URL(p, ROOT), "utf8");
export const slug = s => String(s).toLowerCase().replace(/&/g, "and").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
export const MEAL_TXT = { l: "lunch", d: "dinner", ld: "lunch and dinner" };

export function loadOrderData() { const ctx = { window: {} }; vm.runInNewContext(read("order-data.js"), ctx); return ctx.window.SX_MENU; }
export const MN_RE = /(<script type="application\/json" id="mn-data">)([\s\S]*?)(<\/script><noscript>)([\s\S]*?)(<\/noscript>)/;
export function loadMenuPage() { const m = read("menu.html").match(MN_RE); if (!m) throw new Error("mn-data block not found in menu.html"); return JSON.parse(m[2]); }

// Name shown for a dish at lunch (l) or dinner (d). A dish may have a different dinner name.
export const nameFor = (d, meal) => (meal === "d" && d.dinnerName) ? d.dinnerName : d.name;
// Flat name used for the server price list: "Lunch name / Dinner name" when they differ.
export const flatName = d => d.dinnerName && d.dinnerName !== d.name ? d.name + " / " + d.dinnerName : d.name;

// ---- Generators. Each takes the validated model { cats, order, dishes } and returns text. ----
// model.dishes[i]: { id, num, name, dinnerName?, sub?, subDinner?, cat, veg, meal, price? , options?:[{key,label,price}], photo?, flag?, soldOut? }

export function genOrderData(model) {
  const items = model.dishes.map(d => {
    const o = { n: d.dinnerName ? { l: d.name, d: d.dinnerName } : d.name, c: d.cat, t: d.veg, m: d.meal };
    if (d.options) o.o = d.options.map(x => [x.label, x.price]); else o.p = d.price;
    if (d.photo) o.i = d.photo; if (d.flag === "s") o.f = d.flag; return o; });   // order popup only knows the "s" (signature) flag
  const cats = {}; model.cats.forEach(c => (cats[c.id] = c.en));
  return "window.SX_MENU=" + JSON.stringify({ cats, order: model.order, items }) + ";\n";
}

export function genServerMenu(model) {
  const items = []; const seen = new Set();
  model.dishes.forEach(d => {
    const opts = d.options || [null];
    opts.forEach((o, oi) => {
      const price = o ? o.price : d.price; const sku = d.id + (o ? "-" + o.key : "");
      if (seen.has(sku)) throw new Error("duplicate sku " + sku); seen.add(sku);
      items.push({ sku, k: d.num + "|" + (d.options ? oi : ""), name: flatName(d) + (o ? " (" + o.label + ")" : ""), cat: d.cat, veg: d.veg, meal: d.meal, priceMinor: Math.round(price * 100), available: !d.soldOut });
    });
  });
  const cats = {}; model.cats.forEach(c => (cats[c.id] = c.en));
  return "// GENERATED by tools/cms-build.mjs from Sanity. Do not edit by hand.\nexport const CATS = " + JSON.stringify(cats) +
    ";\nexport const ITEMS = " + JSON.stringify(items).replace(/\},\{/g, "},\n{") + ";\n";
}

export function genMenuPage(model, imgs) {
  const cats = {}; model.cats.forEach(c => (cats[c.id] = { te: c.te, en: c.en, ic: c.ic }));
  const items = model.dishes.map(d => {
    const o = { c: d.cat, n: d.dinnerName ? { l: d.name, d: d.dinnerName } : d.name, t: d.veg, m: d.meal };
    const s = d.subDinner && d.subDinner !== d.sub ? { l: d.sub, d: d.subDinner } : d.sub; if (s) o.s = s;
    if (d.options) o.o = d.options.map(x => [x.label, x.price]); else o.p = d.price;
    if (d.flag) o.f = d.flag; if (d.photo) o.i = d.photo; return o; });
  const keep = {}; Object.keys(imgs || {}).sort().forEach(k => { if (model.dishes.some(d => d.photo === k)) keep[k] = imgs[k]; });
  return JSON.stringify({ cats, order: model.order, items, imgs: keep });
}

export function genNoscript(model) {
  const fmt = (d, meal) => {
    const sub = d.subDinner ? "" : d.sub;   // lunch/dinner-specific sub-lines are left out of the no-JavaScript list
    const price = d.options ? d.options.map(x => x.label + " ₹" + x.price).join(" / ") : "₹" + d.price;
    return "<li>" + nameFor(d, meal) + (sub ? " (" + sub + ")" : "") + " - " + price + " - " + MEAL_TXT[meal] + "</li>"; };
  let h = '<div class="w"><p>Menu (enable JavaScript for the interactive version with filters and search).</p>';
  model.cats.forEach(c => {
    const ds = model.dishes.filter(d => d.cat === c.id); if (!ds.length) return;
    h += "<h3>" + c.en + "</h3><ul>";
    ds.forEach(d => { if (d.dinnerName && d.dinnerName !== d.name && d.meal === "ld") h += fmt(d, "l").replace(/ - lunch and dinner<\/li>$/, " - lunch</li>") + fmt(d, "d").replace(/ - lunch and dinner<\/li>$/, " - dinner</li>"); else h += fmt(d, d.meal === "d" ? "d" : "l").replace(/ - (lunch|dinner|lunch and dinner)<\/li>$/, " - " + MEAL_TXT[d.meal] + "</li>"); });
    h += "</ul>"; });
  return h + "</div>";
}

// schema.org Menu inside menu.html (what Google reads). Only the dish sections are rebuilt; the rest of the block is kept.
const LD_RE = /(<script type="application\/ld\+json"[^>]*>)([\s\S]*?)(<\/script>)/;
export function genJsonLd(html, model) {
  const m = html.match(LD_RE); if (!m) throw new Error("JSON-LD block not found in menu.html");
  const j = JSON.parse(m[2]); const menu = (j["@graph"] || []).find(x => x["@type"] === "Menu"); if (!menu) throw new Error("Menu entry not found in JSON-LD");
  const origin = new URL(menu.url).origin; const item = (d, name, mealKey) => {
    const sub = d.subDinner ? "" : d.sub; const o = { "@type": "MenuItem", name, description: (sub ? sub + ". " : "") + MEAL_TXT[mealKey][0].toUpperCase() + MEAL_TXT[mealKey].slice(1) };
    if (d.veg === "v") o.suitableForDiet = "https://schema.org/VegetarianDiet";
    const offer = (label, price) => Object.assign({ "@type": "Offer" }, label ? { name: label } : {}, { price: String(price), priceCurrency: "INR" });
    o.offers = d.options ? d.options.map(x => offer(x.label, x.price)) : offer(null, d.price);
    if (d.photo) o.image = origin + "/assets/dishes/" + d.photo + ".webp"; return o; };
  menu.hasMenuSection = model.cats.map(c => ({ "@type": "MenuSection", name: c.en, hasMenuItem: model.dishes.filter(d => d.cat === c.id).flatMap(d =>
    d.dinnerName && d.dinnerName !== d.name && d.meal === "ld" ? [item(d, d.name, "l"), item(d, d.dinnerName, "d")] : [item(d, d.name, d.meal)]) })).filter(s => s.hasMenuItem.length);
  return html.replace(LD_RE, (_, a, _b, c) => a + JSON.stringify(j) + c);
}
export function applyMenuPage(html, model) {
  const m = html.match(MN_RE); if (!m) throw new Error("mn-data block not found in menu.html");
  const old = JSON.parse(m[2]);
  const out = html.replace(MN_RE, (_, a, _b, c, _d, e) => a + genMenuPage(model, old.imgs) + c + genNoscript(model) + e);
  return genJsonLd(out, model);
}
