// ---- Validation: every rule that must hold before a build may write anything. ----
export function validate(model) {
  const bad = []; const E = m => bad.push(m);
  const catIds = new Set(model.cats.map(c => c.id));
  if (!model.cats.length) E("no categories");
  model.cats.forEach(c => { if (!c.en || !c.te) E("category " + c.id + ": needs English and Telugu name"); if (!(c.ic >= 1 && c.ic <= 6)) E("category " + c.id + ": icon must be 1 to 6"); });
  const skus = new Set(), nums = new Set();
  model.dishes.forEach(d => {
    const w = "dish " + (d.name || d.id);
    if (!/^[a-z0-9][a-z0-9-]*$/.test(d.id || "")) E(w + ": bad id"); 
    if (nums.has(d.num)) E(w + ": duplicate number " + d.num); nums.add(d.num);
    if (!d.name || !d.name.trim()) E(w + ": name is empty");
    if (!catIds.has(d.cat)) E(w + ": unknown category " + d.cat);
    if (!["v", "n", "e"].includes(d.veg)) E(w + ": veg / non-veg / egg missing");
    if (!["l", "d", "ld"].includes(d.meal)) E(w + ": lunch / dinner / both missing");
    if (d.options) { if (d.options.length < 2) E(w + ": size options need at least 2"); const ks = new Set();
      d.options.forEach(o => { if (!o.label) E(w + ": option without a label"); if (!(o.price > 0) || !Number.isInteger(o.price)) E(w + ": option " + o.label + " price must be whole rupees above 0"); if (ks.has(o.key)) E(w + ": duplicate option key " + o.key); ks.add(o.key); }); }
    else if (!(d.price > 0) || !Number.isInteger(d.price)) E(w + ": price must be whole rupees above 0");
    (d.options ? d.options.map(o => d.id + "-" + o.key) : [d.id]).forEach(k => { if (skus.has(k)) E(w + ": duplicate item code " + k); skus.add(k); });
  });
  ["l", "d"].forEach(meal => (model.order[meal] || []).forEach(cid => {
    if (!catIds.has(cid)) E("order." + meal + ": unknown category " + cid);
    else if (!model.dishes.some(d => d.cat === cid && d.meal.includes(meal))) E("category " + cid + " is shown at " + (meal === "l" ? "lunch" : "dinner") + " but has no dish for it"); }));
  ["l", "d"].forEach(meal => { if (!(model.order[meal] || []).length) E("no visible category for " + (meal === "l" ? "lunch" : "dinner")); });
  return bad;
}

// ---- Baseline: today's files turned into the model (used by the seed script and the equality test). ----
export function baselineModel() {
  const M = loadOrderData(), P = loadMenuPage(), srv = read("functions/_lib/menu-data.js");
  const skuByIdx = {}; JSON.parse(srv.split("export const ITEMS = ")[1].replace(/;\s*$/, "")).forEach(it => { const [i] = it.k.split("|"); (skuByIdx[i] = skuByIdx[i] || []).push(it.sku); });
  const cats = Object.keys(P.cats).map(id => ({ id, te: P.cats[id].te, en: P.cats[id].en, ic: P.cats[id].ic }));
  const dishes = M.items.map((it, idx) => {
    const pg = P.items[idx], skus = skuByIdx[idx];
    const d = { num: idx, cat: it.c, veg: it.t, meal: it.m };
    if (typeof it.n === "string") d.name = it.n; else { d.name = it.n.l; d.dinnerName = it.n.d; }
    if (pg.s != null) { if (typeof pg.s === "string") d.sub = pg.s; else { d.sub = pg.s.l; d.subDinner = pg.s.d; } }
    if (it.i) d.photo = it.i; if (pg.f) d.flag = pg.f;
    if ((it.f || "") !== (pg.f === "s" ? "s" : "")) throw new Error("flag mismatch on " + d.name);
    if (it.o) { d.options = it.o.map(([label, price]) => ({ label, price, key: slug(label) }));
      const base = skus[0].slice(0, skus[0].length - ("-" + d.options[0].key).length);
      d.id = base; d.options.forEach((o, i) => { if (skus[i] !== base + "-" + o.key) throw new Error("sku mismatch " + skus[i]); }); }
    else { d.price = it.p; d.id = skus[0]; }
    return d; });
  return { cats, order: M.order, dishes };
}

// ---- Sanity documents <-> model ----
const strip = o => { Object.keys(o).forEach(k => o[k] === undefined && delete o[k]); return o; };
export function toSanityDocs(model) {
  const docs = [];
  model.cats.forEach((c, i) => docs.push({ _id: "cat." + c.id, _type: "category", code: c.id, nameEn: c.en, nameTe: c.te, icon: c.ic, order: (i + 1) * 10, showLunch: model.order.l.includes(c.id), showDinner: model.order.d.includes(c.id),
    orderLunch: model.order.l.indexOf(c.id) + 1 || undefined, orderDinner: model.order.d.indexOf(c.id) + 1 || undefined }));
  model.dishes.forEach((d, i) => docs.push(strip({ _id: "dish." + d.num, _type: "dish", dishId: d.id, num: d.num, name: d.name, dinnerName: d.dinnerName, subtitle: d.sub, subtitleDinner: d.subDinner,
    category: { _type: "reference", _ref: "cat." + d.cat }, diet: d.veg, meal: d.meal, price: d.price, options: d.options && d.options.map(o => ({ _type: "sizeOption", _key: o.key, key: o.key, label: o.label, price: o.price })),
    photoKey: d.photo, tag: d.flag, soldOut: false, order: (i + 1) * 10 })));
  return docs;
}
export function modelFromSanity(raw) {
  const cats = (raw.categories || []).slice().sort((a, b) => a.order - b.order).map(c => ({ id: c.code, te: c.nameTe, en: c.nameEn, ic: c.icon, _c: c }));
  const order = { l: [], d: [] };
  [["l", "showLunch", "orderLunch"], ["d", "showDinner", "orderDinner"]].forEach(([m, show, ord]) =>
    order[m] = cats.filter(c => c._c[show]).sort((a, b) => (a._c[ord] || 999) - (b._c[ord] || 999)).map(c => c.id));
  const byRef = new Map((raw.categories || []).map(c => [c._id, c.code]));
  const src = (raw.dishes || []).filter(d => !d.hidden).slice().sort((a, b) => a.order - b.order);
  let next = Math.max(-1, ...src.map(d => d.num == null ? -1 : d.num)) + 1;
  src.filter(d => d.num == null).sort((a, b) => String(a._createdAt).localeCompare(String(b._createdAt))).forEach(d => (d._num = next++));
  const dishes = src.map(d => strip({ id: d.dishId, num: d.num != null ? d.num : d._num, name: (d.name || "").trim(), dinnerName: d.dinnerName ? d.dinnerName.trim() : undefined, sub: d.subtitle || undefined, subDinner: d.subtitleDinner || undefined,
    cat: byRef.get(d.category && d.category._ref), veg: d.diet, meal: d.meal, price: d.options && d.options.length ? undefined : d.price,
    options: d.options && d.options.length ? d.options.map(o => ({ key: o.key, label: o.label, price: o.price })) : undefined, photo: d.photoKey || undefined, flag: d.tag || undefined, soldOut: d.soldOut || undefined }));
  cats.forEach(c => delete c._c);
  return { cats, order, dishes };
}

// ---- ID lock: a dish keeps its number and code for ever, even if renamed, hidden or deleted. ----
// lock = { "<sanity _id>": { num, id } }. New dishes get the next free number. A changed dishId stops the build.
export function applyIdLock(raw, lock) {
  const next = JSON.parse(JSON.stringify(lock)); const used = Object.values(next).map(x => x.num);
  let n = Math.max(-1, ...used) + 1;
  raw.dishes.slice().sort((a, b) => String(a._createdAt).localeCompare(String(b._createdAt))).forEach(d => {
    const L = next[d._id];
    if (L) { if (d.dishId !== L.id) throw new Error("Dish code changed for " + (d.name || d._id) + ": was " + L.id + ", now " + d.dishId + ". Codes never change, so orders and Reelo keep matching. Put the old code back."); d.num = L.num; }
    else { if (!d.dishId) throw new Error("New dish " + (d.name || d._id) + " has no code (the Code field is empty)."); d.num = n; next[d._id] = { num: n++, id: d.dishId }; }
  });
  return next;
}
