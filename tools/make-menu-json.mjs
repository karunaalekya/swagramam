// Builds functions/_lib/menu-data.js (the server price list) from order-data.js. Run: node tools/make-menu-json.mjs
import fs from "node:fs"; import vm from "node:vm";
const src = fs.readFileSync(new URL("../order-data.js", import.meta.url), "utf8");
const ctx = { window: {} }; vm.runInNewContext(src, ctx);
const M = ctx.window.SX_MENU;
const slug = s => String(s).toLowerCase().replace(/&/g, "and").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const nm = it => typeof it.n === "string" ? it.n : (it.n.l && it.n.d && it.n.l !== it.n.d ? it.n.l + " / " + it.n.d : (it.n.l || it.n.d));
const seen = new Set(), items = [];
const uniq = s => { let x = s, i = 2; while (seen.has(x)) x = s + "-" + i++; seen.add(x); return x; };
M.items.forEach((it, idx) => {
  const opts = it.o || [null];
  opts.forEach((o, oi) => {
    const price = o ? o[1] : it.p;
    if (!(price > 0)) throw new Error("no price: " + nm(it));
    items.push({ sku: uniq(slug(nm(it)) + (o ? "-" + slug(o[0]) : "")), k: idx + "|" + (it.o ? oi : ""),
      name: nm(it) + (o ? " (" + o[0] + ")" : ""), cat: it.c, veg: it.t, meal: it.m, priceMinor: Math.round(price * 100), available: true });
  });
});
const out = "// GENERATED by tools/make-menu-json.mjs from order-data.js. Do not edit by hand.\nexport const CATS = " + JSON.stringify(M.cats) +
  ";\nexport const ITEMS = " + JSON.stringify(items, null, 0).replace(/\},\{/g, "},\n{") + ";\n";
fs.writeFileSync(new URL("../functions/_lib/menu-data.js", import.meta.url), out);
console.log("items:", items.length, "dishes:", M.items.length);
